"""The manual is one whole in two languages, with pictures (task -028; UC NF11, SPEC AK21).

Every screen chapter shows its screen, English and German say the same, the pictures exist, are
1440 px wide and small, and each of them can be regenerated by ``tools/screenshots.py``.
"""

from __future__ import annotations

import re
import struct
from pathlib import Path

import pytest

import screenshots
from check_manual_coverage import LANGUAGES, ROOT, discover_routes

MANUAL = ROOT / "docs" / "manual"
ASSETS = ROOT / "docs" / "assets" / "screenshots"
IMAGE = re.compile(r"!\[[^\]]*\]\((?P<src>[^)\s]+)\)")
HEADING = re.compile(r"^#{1,6} ", re.MULTILINE)
CHAPTER_LINK = re.compile(r"\]\(([a-z0-9-]+)\.md(?:#[^)]*)?\)")

# Chapters that are not a screen, with the reason a picture would be dishonest or pointless there.
NO_PICTURE = {
    "faq": "questions and answers",
    "glossary": "a word list",
}

# The installer pictures are not made by tools/screenshots.py: they come from the Windows Sandbox
# run (tools/sandbox/run_protocol.py) and are kept in docs/assets/qa/install/rc4/. Each picture in
# the manual is that original, on a 1440 px wide canvas (or scaled to 1440 px). The English pictures
# serve the German chapter too, because the sandbox ran in English.
INSTALL_PICTURES_SOURCE = "Windows-Sandbox run, tools/sandbox/run_protocol.py"
INSTALL_ORIGINALS = ROOT / "docs" / "assets" / "qa" / "install" / "rc4"
INSTALL_PICTURES = {
    "install-wizard-language.png": "03-language.png",
    "install-wizard-folder.png": "03-folder.png",
    "install-wizard-tasks.png": "03-tasks.png",
    "install-wizard-ready.png": "03-ready.png",
    "install-wizard-finish.png": "03-finish.png",
    "install-tray-menu.png": "06-tray-menu.png",
    "install-update-asks-to-close.png": "13b-setup-asks-to-close.png",
    "install-uninstall-question.png": "15-uninstall-question.png",
    "install-uninstall-done.png": "15-uninstall-done.png",
}


def _chapters(lang: str) -> dict[str, str]:
    return {path.stem: path.read_text(encoding="utf-8") for path in sorted((MANUAL / lang).glob("*.md"))}


def _order(text: str) -> int:
    """The `order` of a chapter's front matter."""
    match = re.search(r"^order:\s*(\d+)", text, re.MULTILINE)
    assert match, "chapter without order"
    return int(match[1])


def _images(text: str) -> list[str]:
    """File names of the pictures a chapter embeds, in order."""
    return [Path(m["src"]).name for m in IMAGE.finditer(text)]


@pytest.mark.parametrize("lang", LANGUAGES)
def test_every_screen_chapter_shows_its_screen(lang: str) -> None:
    """Oracle: spec-anchored — task -028 "jedes Kapitel mit Screenshot" and UC NF11: each screen's
    chapter embeds at least one picture, from the language's own folder, and the file exists."""
    chapters = _chapters(lang)
    screens = {route.chapter for route in discover_routes()}
    assert screens, "no screens found"
    for slug in sorted(screens | {"weekly-routine"}):
        text = chapters[slug]
        sources = [m["src"] for m in IMAGE.finditer(text)]
        assert sources, f"{lang}/{slug}.md shows no screenshot"
        for source in sources:
            assert source.startswith(f"../../assets/screenshots/{lang}/"), f"{lang}/{slug}.md: {source}"
            assert (MANUAL / lang / source).resolve().is_file(), f"{lang}/{slug}.md: {source} does not exist"
    for slug, reason in NO_PICTURE.items():
        assert slug in chapters, reason


def test_english_and_german_chapters_are_content_equal() -> None:
    """Oracle: spec-anchored — task -028 "docs/manual/en und docs/manual/de bleiben inhaltsgleich":
    the same chapters, and in each the same number of headings, the same pictures in the same order
    and the same links to other chapters."""
    english, german = _chapters("en"), _chapters("de")
    assert english.keys() == german.keys()
    for slug in english:
        assert len(HEADING.findall(english[slug])) == len(HEADING.findall(german[slug])), f"headings of {slug}"
        assert _images(english[slug]) == _images(german[slug]), f"pictures of {slug}"
        assert sorted(CHAPTER_LINK.findall(english[slug])) == sorted(CHAPTER_LINK.findall(german[slug])), (
            f"links of {slug}"
        )


def test_the_manual_has_an_entry_chapter_questions_and_a_glossary() -> None:
    """Oracle: spec-anchored — task -028 "Einstiegskapitel „Das Wochenritual“ … Fragen-und-Antworten
    und ein Glossar", UC NF11 "Einstieg, jeder UC als Kapitel, Fragen und Antworten": the three
    chapters exist in both languages, sit where a reader expects them, and the start page links them."""
    titles = {"en": ("The weekly routine", "Questions and answers", "Glossary")}
    titles["de"] = ("Das Wochenritual", "Fragen und Antworten", "Glossar")
    for lang in LANGUAGES:
        chapters = _chapters(lang)
        for slug, title in zip(("weekly-routine", "faq", "glossary"), titles[lang], strict=True):
            assert re.search(rf"^# {re.escape(title)}$", chapters[slug], re.MULTILINE), f"{lang}/{slug}"
            assert f"]({slug}.md)" in chapters["index"], f"{lang}/index.md does not link {slug}"
        order = {slug: _order(text) for slug, text in chapters.items()}
        assert order["first-run"] < order["weekly-routine"] < order["entry"]
        assert order["backup"] < order["faq"] < order["glossary"] < order["manual"]


def test_no_screenshot_is_missing_or_orphaned() -> None:
    """Oracle: spec-anchored — task -028: the pictures in the repository are exactly those the
    chapters embed, in both languages (a picture nobody shows is dead weight in a public repository)."""
    embedded = {lang: {n for text in _chapters(lang).values() for n in _images(text)} for lang in LANGUAGES}
    assert embedded["en"] == embedded["de"]
    for lang in LANGUAGES:
        on_disk = {path.name for path in (ASSETS / lang).iterdir()}
        assert on_disk == embedded[lang], f"{lang}: {sorted(on_disk ^ embedded[lang])}"


@pytest.mark.parametrize("lang", LANGUAGES)
def test_screenshots_are_desktop_width_and_small(lang: str) -> None:
    """Oracle: spec-anchored — task -028 "Desktop 1440 px" and the repository's large-file gate
    (check-added-large-files: 500 KB): a PNG whose header says 1440 px wide and that stays below 400 KB."""
    for path in sorted((ASSETS / lang).glob("*.png")):
        data = path.read_bytes()
        assert data[:8] == b"\x89PNG\r\n\x1a\n", path.name
        width, height = struct.unpack(">II", data[16:24])
        assert width == screenshots.WIDTH == 1440, path.name
        assert 600 <= height <= 1600, f"{path.name}: {height}"
        assert len(data) < 400_000, f"{path.name}: {len(data)} bytes"


def test_every_picture_can_be_regenerated() -> None:
    """Oracle: spec-anchored — task -028 "Der Demo-Datensatz wird im Repo reproduzierbar erzeugt … damit
    ein Folge-Release dieselben Bilder neu bauen kann": every embedded picture is a screen or wizard
    step that tools/screenshots.py produces, under the file name the chapter uses."""
    producible = {f"{shot.name}.png" for shot in screenshots._screens()} | {
        f"{n}.png" for n in screenshots.WIZARD_SHOTS
    }
    for lang in LANGUAGES:
        embedded = {n for text in _chapters(lang).values() for n in _images(text)}
        installer = {n for n in embedded if n.startswith("install-")}
        assert installer == set(INSTALL_PICTURES), sorted(installer ^ set(INSTALL_PICTURES))
        assert embedded - installer <= producible, sorted(embedded - installer - producible)


def test_every_installer_picture_has_its_original_from_the_sandbox_run() -> None:
    """Oracle: spec-anchored — task -025 "jedes install-*.png hat ein Gegenstück unter
    docs/assets/qa/install/rc4/": the pictures that tools/screenshots.py cannot make come from the
    sandbox run (INSTALL_PICTURES_SOURCE), each from one original that stays in place, and nothing
    else in the screenshot folders starts with `install-`."""
    assert "run_protocol.py" in INSTALL_PICTURES_SOURCE
    assert len(set(INSTALL_PICTURES.values())) == len(INSTALL_PICTURES)
    for name, original in INSTALL_PICTURES.items():
        assert (INSTALL_ORIGINALS / original).is_file(), f"{name}: {original} is missing"
    for lang in LANGUAGES:
        on_disk = {path.name for path in (ASSETS / lang).glob("install-*.png")}
        assert on_disk == set(INSTALL_PICTURES), f"{lang}: {sorted(on_disk ^ set(INSTALL_PICTURES))}"
    assert all(
        (ASSETS / "en" / name).read_bytes() == (ASSETS / "de" / name).read_bytes() for name in INSTALL_PICTURES
    ), "the German chapter shows the English pictures"
